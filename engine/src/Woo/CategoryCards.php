<?php
/**
 * Product category cards.
 *
 * @package Pergel
 */

declare( strict_types=1 );

namespace Pergel\Woo;

/**
 * Links to product categories in four styles, for the category strip above
 * the products (ShopHeader) and the Category cards block:
 *
 * - images: a round picture with the name under it;
 * - boxes: a box with the picture, the name and the number of products;
 * - list: a box with the name, the first subcategories and the picture;
 * - names: the names as pills.
 *
 * Empty categories and the default category are left out. Pictures come
 * from the category image; a category without one shows its first letter.
 * The CSS is the block's style, which the strip loads as well.
 */
final class CategoryCards {

	/**
	 * The styles.
	 */
	public const STYLES = array( 'images', 'boxes', 'list', 'names' );

	/**
	 * Most categories drawn.
	 */
	public const MOST = 24;

	/**
	 * Subcategories in a "list" box.
	 */
	private const CHILDREN = 4;

	/**
	 * Style handle of the block, generated by WordPress from its block.json.
	 */
	public const STYLE_HANDLE = 'pergel-category-cards-style';

	/**
	 * The child categories of a category (0: the main categories).
	 *
	 * @param int $above Parent category id.
	 * @param int $number Most categories.
	 * @return list<\WP_Term>
	 */
	public static function terms( int $above, int $number ): array {
		$terms   = get_terms(
			array(
				'taxonomy'   => 'product_cat',
				'parent'     => $above,
				'hide_empty' => true,
				'menu_order' => 'ASC',
				'number'     => $number + 1,
			)
		);
		$default = (int) get_option( 'default_product_cat', 0 );
		$list    = array();
		foreach ( is_array( $terms ) ? $terms : array() as $term ) {
			// "Uncategorized" stays out.
			if ( $term instanceof \WP_Term && $term->term_id !== $default && count( $list ) < $number ) {
				$list[] = $term;
			}
		}
		return $list;
	}

	/**
	 * The list items of the cards.
	 *
	 * @param array  $terms Categories.
	 * @param string $style One of STYLES.
	 * @phpstan-param list<\WP_Term> $terms
	 */
	public static function items( array $terms, string $style ): string {
		$items = '';
		foreach ( $terms as $term ) {
			$link = get_term_link( $term );
			if ( ! is_string( $link ) ) {
				continue;
			}
			$picture = 'names' === $style ? '' : self::picture( $term );
			$count   = 'boxes' === $style
				/* translators: %s: number of products. */
				? sprintf( '<span class="pergel-category-card__count">%s</span>', esc_html( sprintf( _n( '%s product', '%s products', (int) $term->count, 'pergel-engine' ), number_format_i18n( (int) $term->count ) ) ) )
				: '';
			$card = sprintf(
				'<a class="pergel-category-card__link" href="%1$s">%2$s<span class="pergel-category-card__name">%3$s</span>%4$s</a>',
				esc_url( $link ),
				'list' === $style ? '' : $picture,
				esc_html( $term->name ),
				$count
			);
			if ( 'list' === $style ) {
				$card = sprintf( '<div class="pergel-category-card__text">%1$s%2$s</div>%3$s', $card, self::children( $term ), $picture );
			}
			$items .= '<li class="pergel-category-card">' . $card . '</li>';
		}
		return $items;
	}

	/**
	 * The first subcategories of a category as links.
	 *
	 * @param \WP_Term $term Category.
	 */
	private static function children( \WP_Term $term ): string {
		$links = '';
		foreach ( self::terms( $term->term_id, self::CHILDREN ) as $child ) {
			$link = get_term_link( $child );
			if ( is_string( $link ) ) {
				$links .= sprintf( '<li><a href="%1$s">%2$s</a></li>', esc_url( $link ), esc_html( $child->name ) );
			}
		}
		return '' === $links ? '' : '<ul class="pergel-category-card__children">' . $links . '</ul>';
	}

	/**
	 * The category image, or its first letter on a plain shape. Decorative:
	 * the name is the link text.
	 *
	 * @param \WP_Term $term Category.
	 */
	private static function picture( \WP_Term $term ): string {
		$image = (int) get_term_meta( $term->term_id, 'thumbnail_id', true );
		$html  = $image > 0 ? wp_get_attachment_image(
			$image,
			'woocommerce_thumbnail',
			false,
			array(
				'class'   => 'pergel-category-card__image',
				'alt'     => '',
				'loading' => 'lazy',
				'sizes'   => '10rem',
			)
		) : '';
		if ( '' !== $html ) {
			return $html;
		}
		return sprintf( '<span class="pergel-category-card__image is-empty" aria-hidden="true">%s</span>', esc_html( mb_substr( $term->name, 0, 1 ) ) );
	}

	/**
	 * The Category cards block.
	 *
	 * @param array<string, mixed> $attributes Block attributes.
	 */
	public static function block( array $attributes ): string {
		$style  = in_array( $attributes['cardStyle'] ?? '', self::STYLES, true ) ? (string) $attributes['cardStyle'] : 'boxes';
		$parent = max( 0, (int) ( $attributes['parent'] ?? 0 ) );
		$number = min( self::MOST, max( 1, (int) ( $attributes['number'] ?? 8 ) ) );
		$items  = self::items( self::terms( $parent, $number ), $style );
		if ( '' === $items ) {
			return '';
		}
		return sprintf(
			'<nav %1$s><ul>%2$s</ul></nav>',
			get_block_wrapper_attributes(
				array(
					'class'      => "pergel-category-cards is-$style",
					'aria-label' => 0 === $parent ? __( 'Product categories', 'pergel-engine' ) : __( 'Subcategories', 'pergel-engine' ),
				)
			),
			$items
		);
	}
}
