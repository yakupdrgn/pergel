<?php
/**
 * The block manifest: every block.json of the engine in one PHP file.
 *
 * @package Pergel
 */

declare( strict_types=1 );

namespace Pergel\Blocks;

/**
 * Reads engine/blocks/<slug>/block.json files, checks them against the
 * engine's block rules and writes engine/blocks/manifest.php. WordPress
 * registers the blocks from that one file (a block metadata collection),
 * so a request reads no JSON. Needs no WordPress: tools/blocks.php runs
 * it in CI.
 */
final class Manifest {

	public const FILE = 'manifest.php';

	/**
	 * Block metadata keyed by folder name, in folder order.
	 *
	 * @param string $dir The blocks directory.
	 * @return array<string, array<string, mixed>>
	 * @throws \RuntimeException When a block breaks a rule; the message lists every problem.
	 */
	public static function build( string $dir ): array {
		$blocks   = array();
		$problems = array();
		foreach ( self::folders( $dir ) as $slug ) {
			$metadata = self::read( "{$dir}/{$slug}/block.json" );
			if ( null === $metadata ) {
				$problems[] = "{$slug}: block.json is missing or not a JSON object";
				continue;
			}
			foreach ( self::problems( $slug, $metadata, "{$dir}/{$slug}" ) as $problem ) {
				$problems[] = "{$slug}: {$problem}";
			}
			unset( $metadata['$schema'] );
			$blocks[ $slug ] = $metadata;
		}
		if ( array() !== $problems ) {
			throw new \RuntimeException( implode( "\n", $problems ) );
		}
		return $blocks;
	}

	/**
	 * Rule violations of one block. Blocks are server-rendered: name
	 * pergel/<folder>, block API 3, the engine's text domain, a category,
	 * and render.php. Without a compiled editor script the editor builds
	 * the block from its attributes (supports.autoRegister, WP 7.0).
	 *
	 * @param string               $slug     Folder name.
	 * @param array<string, mixed> $metadata Decoded block.json.
	 * @param string               $folder   Folder path.
	 * @return list<string>
	 */
	public static function problems( string $slug, array $metadata, string $folder ): array {
		$problems = array();
		if ( 1 !== preg_match( '/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/', $slug ) ) {
			$problems[] = 'folder name must be lowercase words joined by hyphens';
		}
		if ( ( $metadata['name'] ?? null ) !== "pergel/{$slug}" ) {
			$problems[] = "name must be \"pergel/{$slug}\"";
		}
		if ( 3 !== ( $metadata['apiVersion'] ?? null ) ) {
			$problems[] = 'apiVersion must be 3';
		}
		if ( 'pergel-engine' !== ( $metadata['textdomain'] ?? null ) ) {
			$problems[] = 'textdomain must be "pergel-engine"';
		}
		if ( ! is_string( $metadata['title'] ?? null ) || '' === $metadata['title'] ) {
			$problems[] = 'title is missing';
		}
		if ( ! is_string( $metadata['category'] ?? null ) || '' === $metadata['category'] ) {
			$problems[] = 'category is missing';
		}
		if ( 'file:./render.php' !== ( $metadata['render'] ?? null ) || ! is_file( "{$folder}/render.php" ) ) {
			$problems[] = 'render must be "file:./render.php" and the file must exist';
		}
		$supports = is_array( $metadata['supports'] ?? null ) ? $metadata['supports'] : array();
		if ( ! isset( $metadata['editorScript'] ) && true !== ( $supports['autoRegister'] ?? null ) ) {
			$problems[] = 'a block without editorScript needs supports.autoRegister: true';
		}
		foreach ( array( 'style', 'editorStyle', 'viewStyle' ) as $field ) {
			foreach ( (array) ( $metadata[ $field ] ?? array() ) as $asset ) {
				if ( is_string( $asset ) && str_starts_with( $asset, 'file:' ) && ! is_file( $folder . '/' . substr( $asset, 5 ) ) ) {
					$problems[] = "{$field} file {$asset} does not exist";
				}
			}
		}
		return $problems;
	}

	/**
	 * The manifest file's contents.
	 *
	 * @param array<string, array<string, mixed>> $blocks Output of build().
	 */
	public static function export( array $blocks ): string {
		return "<?php\n"
			. "/**\n * Generated by tools/blocks.php from engine/blocks/<slug>/block.json. Do not edit.\n *\n * @package Pergel\n */\n\n"
			. "// phpcs:ignoreFile\n\n"
			. 'return ' . var_export( $blocks, true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- Writes a PHP file.
	}

	/**
	 * Writes the manifest, or with $check only compares it.
	 *
	 * @param string $dir   The blocks directory.
	 * @param bool   $check Compare only.
	 * @return bool Whether the file on disk was (or, with $check, would be) different.
	 */
	public static function sync( string $dir, bool $check = false ): bool {
		$file     = "{$dir}/" . self::FILE;
		$contents = self::export( self::build( $dir ) );
		$current  = is_file( $file ) ? str_replace( "\r\n", "\n", (string) file_get_contents( $file ) ) : null; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file.
		if ( $current === $contents ) {
			return false;
		}
		if ( ! $check ) {
			file_put_contents( $file, $contents ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- Dev tool.
		}
		return true;
	}

	/**
	 * Block folder names, sorted.
	 *
	 * @param string $dir The blocks directory.
	 * @return list<string>
	 */
	private static function folders( string $dir ): array {
		$folders = array();
		foreach ( (array) scandir( $dir ) as $name ) {
			if ( is_string( $name ) && ! str_starts_with( $name, '.' ) && is_dir( "{$dir}/{$name}" ) ) {
				$folders[] = $name;
			}
		}
		sort( $folders );
		return $folders;
	}

	/**
	 * A decoded block.json, or null.
	 *
	 * @param string $file Path.
	 * @return array<string, mixed>|null
	 */
	private static function read( string $file ): ?array {
		if ( ! is_file( $file ) ) {
			return null;
		}
		$data = json_decode( (string) file_get_contents( $file ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file.
		return is_array( $data ) && ! array_is_list( $data ) ? $data : null;
	}
}
